#!/usr/bin/env node
// Vendors ic-git's verification core into site/lib/ic-git-core.js.
//
//   node tools/sync-ic-git-core.mjs [--from ../ic-git]          # rewrite
//   node tools/sync-ic-git-core.mjs [--from ../ic-git] --check  # exit 1 if out of step
//   node tools/sync-ic-git-core.mjs --verify                     # no checkout: the
//                                   embedded blocks hash to what the header says
//
// What is vendored, byte for byte, from an ic-git checkout:
//
//   core/bls12-381.js   the BLS12-381 verifier (a generated bundle of
//                       @noble/curves; ic-git regenerates it, nobody edits it)
//   core/verifier.js    the core: `Verifier.readCanisterState` reads a
//                       canister's module hash and controllers out of a state
//                       certificate the IC signed, checked against the pinned
//                       NNS root key through the subnet delegation
//                       (ic-git docs/CERTIFIED.md)
//
// Why a copy and not an import: the ballot page is served from a commit and
// pinned by hash, and tools/stage-site.mjs links every module the page runs
// into one file so that one integrity hash covers all of it. A fetch from
// another origin at run time would be code nothing pinned. So the core is a
// file in this tree, reviewed with the rest, and this tool is how it moves:
// the header names the ic-git commit it came from and the sha256 of each
// block, so a reviewer can diff the copy against that commit, and `--verify`
// checks the blocks against the header without a checkout.
//
// The two files are classic scripts (`var NobleBls`, `const Verifier`), not
// modules. Concatenated into one file they share a scope, which is how the
// core finds NobleBls, and one `export` line at the end makes the file a
// module the site can import and the linker can pin. The copy is refused if
// either file carries a line the linker would misread (an import or export
// at the start of a line), so a future ic-git change cannot slip past as a
// half-linked bundle.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const OUT = new URL("../site/lib/ic-git-core.js", import.meta.url);
const BLOCKS = [
  { file: "core/bls12-381.js", start: "// === bls ===", end: "// === end bls ===" },
  { file: "core/verifier.js", start: "// === core ===", end: "// === end core ===" },
];

function fail(msg) {
  console.error(`sync-ic-git-core: ${msg}`);
  process.exit(2);
}

const argv = process.argv.slice(2);
let from = "../ic-git";
let mode = "write";
for (let i = 0; i < argv.length; i++) {
  switch (argv[i]) {
    case "--from": from = argv[++i] ?? fail("--from needs a path"); break;
    case "--check": mode = "check"; break;
    case "--verify": mode = "verify"; break;
    default: fail(`unknown arg: ${argv[i]}`);
  }
}

const sha256 = (text) => createHash("sha256").update(text).digest("hex");

// The header is the copy's provenance; `--verify` reads it back.
const HEADER = /^\/\/ GENERATED by tools\/sync-ic-git-core\.mjs from ic-git commit ([0-9a-f]{40}); do not edit\.\n\/\/ core\/bls12-381\.js sha256 ([0-9a-f]{64})\n\/\/ core\/verifier\.js sha256 ([0-9a-f]{64})\n/;

function blocksOf(text) {
  // Each block is delimited by its own markers, which the ic-git files
  // start and end with. Everything between the header and the export line
  // must be exactly the two blocks.
  const out = [];
  for (const b of BLOCKS) {
    const a = text.indexOf(b.start);
    const z = text.indexOf(b.end);
    if (a === -1 || z === -1 || z < a) fail(`site/lib/ic-git-core.js has no ${b.start} block`);
    out.push(text.slice(a, z + b.end.length));
  }
  return out;
}

if (mode === "verify") {
  if (!existsSync(OUT)) fail("site/lib/ic-git-core.js does not exist");
  const text = readFileSync(OUT, "utf8");
  const m = HEADER.exec(text);
  if (!m) fail("site/lib/ic-git-core.js has no provenance header");
  const [bls, core] = blocksOf(text);
  const problems = [];
  if (sha256(bls) !== m[2]) problems.push(`core/bls12-381.js block hashes to ${sha256(bls)}, header says ${m[2]}`);
  if (sha256(core) !== m[3]) problems.push(`core/verifier.js block hashes to ${sha256(core)}, header says ${m[3]}`);
  if (problems.length) fail(problems.join("\n  "));
  console.log(`site/lib/ic-git-core.js: blocks match the header (ic-git commit ${m[1]})`);
  process.exit(0);
}

const git = (...args) => execFileSync("git", ["-C", from, ...args], { encoding: "utf8" }).trim();
if (!existsSync(`${from}/core/verifier.js`)) fail(`${from} is not an ic-git checkout (no core/verifier.js); pass --from`);
// The commit recorded is the last one that touched core/, whatever branch
// the checkout is on, so the header does not change with unrelated commits.
// A dirty core/ has no commit to name.
if (git("status", "--porcelain", "--", "core/")) fail(`${from}/core has uncommitted changes; commit them in ic-git first`);
const commit = git("log", "-1", "--format=%H", "--", "core/");

const texts = BLOCKS.map((b) => {
  const text = readFileSync(`${from}/${b.file}`, "utf8").replace(/\n$/, "");
  if (!text.startsWith(b.start) || !text.endsWith(b.end)) fail(`${b.file} must start with "${b.start}" and end with "${b.end}"`);
  // The site's linker (tools/stage-site.mjs) reads `import`/`export` at the
  // start of a line as module syntax, and refuses import() and import.meta.
  const bad = /^(import|export)\b/m.exec(text) ?? /\bimport\s*\(|\bimport\.meta\b/.exec(text);
  if (bad) fail(`${b.file} contains \`${bad[0]}\`, which the linker would misread`);
  for (const ch of text) if (ch.charCodeAt(0) > 0x7f) fail(`${b.file} is not pure ASCII (tools/check-ascii.mjs)`);
  return text;
});

const want =
  `// GENERATED by tools/sync-ic-git-core.mjs from ic-git commit ${commit}; do not edit.\n` +
  `// core/bls12-381.js sha256 ${sha256(texts[0])}\n` +
  `// core/verifier.js sha256 ${sha256(texts[1])}\n` +
  `//\n` +
  `// ic-git's verification core, vendored whole: the BLS12-381 verifier and\n` +
  `// the core that uses it to read a canister's module hash and controllers\n` +
  `// out of a state certificate the IC signed (ic-git docs/CERTIFIED.md).\n` +
  `// This page uses Verifier.readCanisterState and Verifier.DEFAULTS; the\n` +
  `// rest of the core rides along so that the copy is the file ic-git\n` +
  `// tests, not an excerpt. To update: node tools/sync-ic-git-core.mjs.\n` +
  `// To check without an ic-git checkout: node tools/sync-ic-git-core.mjs --verify.\n` +
  `${texts[0]}\n${texts[1]}\nexport { Verifier };\n`;

const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (mode === "check") {
  if (now !== want) {
    console.error(`site/lib/ic-git-core.js is out of step with ${from} (commit ${commit}): run node tools/sync-ic-git-core.mjs`);
    process.exit(1);
  }
  console.log(`site/lib/ic-git-core.js is in step with ${from} (commit ${commit})`);
} else if (now === want) {
  console.log("site/lib/ic-git-core.js already in step");
} else {
  writeFileSync(OUT, want);
  console.log(`synced site/lib/ic-git-core.js from ${from} (commit ${commit})`);
}
